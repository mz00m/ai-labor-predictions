import confirmedSources from "@/data/confirmed-sources.json";
import { getAllPredictions } from "./data-loader";
import type { EvidenceTier } from "./types";

/* ------------------------------------------------------------------ */
/*  Types                                                              */
/* ------------------------------------------------------------------ */

interface RawSource {
  id: string;
  title: string;
  publisher: string;
  excerpt?: string;
  evidenceTier: number;
  usedIn: string[];
  datePublished: string;
  url?: string;
  verified?: boolean;
  synthetic?: boolean;
  _action?: string;
}

export interface SearchResult {
  id: string;
  title: string;
  publisher: string;
  excerpt: string;
  evidenceTier: EvidenceTier;
  usedIn: string[];
  datePublished: string;
  url?: string;
}

/* ------------------------------------------------------------------ */
/*  Pre-compute flat source array + slug→title map at module load      */
/* ------------------------------------------------------------------ */

const allSources: SearchResult[] = Object.values(
  (confirmedSources as { sources: Record<string, RawSource> }).sources
)
  .filter((s) => s._action !== "REMOVE")
  .map((s) => ({
    id: s.id,
    title: s.title,
    publisher: s.publisher,
    excerpt: s.excerpt ?? "",
    evidenceTier: s.evidenceTier as EvidenceTier,
    usedIn: s.usedIn,
    datePublished: s.datePublished,
    url: s.url,
  }));

const slugToTitle: Record<string, string> = {};
for (const p of getAllPredictions()) {
  slugToTitle[p.slug] = p.title;
}

/* ------------------------------------------------------------------ */
/*  Search index: pre-built full-text haystacks (lazy-loaded)          */
/* ------------------------------------------------------------------ */

/**
 * Lightweight fallback haystacks built from confirmed-sources.json only.
 * Used until the full search index (with source-content abstracts,
 * key findings, etc.) loads via dynamic import.
 */
function buildBasicHaystacks(): Map<string, string> {
  const extra: Record<string, string[]> = {};
  for (const p of getAllPredictions()) {
    for (const s of p.sources) {
      if (s.excerpt) {
        (extra[s.id] ??= []).push(s.excerpt);
      }
    }
    for (const o of p.overlays ?? []) {
      if (o.label) {
        for (const sid of o.sourceIds) {
          (extra[sid] ??= []).push(o.label);
        }
      }
    }
  }

  const map = new Map<string, string>();
  for (const source of allSources) {
    const parts = [source.title, source.publisher, source.excerpt];
    const extraTexts = extra[source.id];
    if (extraTexts) {
      parts.push(Array.from(new Set(extraTexts)).join(" "));
    }
    map.set(source.id, parts.join(" ").toLowerCase());
  }
  return map;
}

/** Starts as basic haystacks, upgraded to full-text on first search. */
let haystacks: Map<string, string> = buildBasicHaystacks();
let fullIndexLoaded = false;
let fullIndexLoading = false;

/**
 * Lazily load the full search index (generated by
 * `scripts/build-search-index.ts`) which includes source-content
 * abstracts, key findings, methodology, and qualifiers.
 *
 * The index is ~730 KB and loaded via dynamic import so it doesn't
 * bloat the initial page bundle.
 */
async function loadFullIndex(): Promise<void> {
  if (fullIndexLoaded || fullIndexLoading) return;
  fullIndexLoading = true;

  try {
    const mod = await import("@/data/search-index.json");
    const index: Record<string, string> = mod.default ?? mod;
    const upgraded = new Map<string, string>();
    for (const source of allSources) {
      upgraded.set(source.id, index[source.id] ?? haystacks.get(source.id) ?? "");
    }
    haystacks = upgraded;
    fullIndexLoaded = true;
  } catch {
    // search-index.json not generated yet - fall back to basic haystacks
  } finally {
    fullIndexLoading = false;
  }
}

/* ------------------------------------------------------------------ */
/*  Public API                                                         */
/* ------------------------------------------------------------------ */

/**
 * Multi-token AND search across all source text.
 *
 * On the first call, triggers a lazy load of the full-text search index
 * (abstracts, key findings, methodology from source-content store).
 * Until loaded, searches the basic haystack (title + publisher + excerpt
 * + prediction-level excerpts + overlay labels).
 *
 * Returns at most `limit` results.
 */
export function searchSources(query: string, limit = 8): SearchResult[] {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return [];

  // Fire-and-forget load of full index - next search will use it
  if (!fullIndexLoaded) {
    loadFullIndex();
  }

  const tokens = trimmed.split(/\s+/);

  return allSources
    .filter((source) => {
      const haystack = haystacks.get(source.id)!;
      return tokens.every((t) => haystack.includes(t));
    })
    .slice(0, limit);
}

/* ------------------------------------------------------------------ */
/*  Ranked retrieval (BM25)                                            */
/* ------------------------------------------------------------------ */

const K1 = 1.5;
const B = 0.75;

let tokenCache: { docs: Map<string, string[]>; avgdl: number } | null = null;

function getDocTokens() {
  if (tokenCache) return tokenCache;
  const docs = new Map<string, string[]>();
  let totalLen = 0;
  haystacks.forEach((hay, id) => {
    const toks = hay.split(/\W+/).filter(Boolean);
    docs.set(id, toks);
    totalLen += toks.length;
  });
  tokenCache = { docs, avgdl: totalLen / Math.max(1, docs.size) };
  return tokenCache;
}

/**
 * BM25-ranked retrieval over the whole active corpus.
 *
 * `searchSources` requires every token to appear, which suits a search box but
 * returns nothing for a conversational query. This ranks instead, so a question
 * phrased in prose still reaches sources — including the ones no prediction
 * graph cites, which are otherwise unreachable outside the search page.
 */
export async function rankSources(query: string, limit = 6): Promise<SearchResult[]> {
  const wasLoaded = fullIndexLoaded;
  await loadFullIndex();
  if (fullIndexLoaded && !wasLoaded) tokenCache = null;

  const terms = query.toLowerCase().split(/\W+/).filter((t) => t.length > 2);
  if (terms.length === 0) return [];

  const { docs, avgdl } = getDocTokens();
  const n = docs.size;
  const scores = new Map<string, number>();

  for (const term of Array.from(new Set(terms))) {
    const tfByDoc = new Map<string, number>();
    docs.forEach((toks, id) => {
      let tf = 0;
      for (const tok of toks) {
        if (tok === term || (term.length > 4 && tok.startsWith(term))) tf++;
      }
      if (tf > 0) tfByDoc.set(id, tf);
    });
    if (tfByDoc.size === 0) continue;

    const idf = Math.log(1 + (n - tfByDoc.size + 0.5) / (tfByDoc.size + 0.5));
    tfByDoc.forEach((tf, id) => {
      const dl = docs.get(id)!.length;
      const norm = (tf * (K1 + 1)) / (tf + K1 * (1 - B + (B * dl) / avgdl));
      scores.set(id, (scores.get(id) ?? 0) + idf * norm);
    });
  }

  const byId = new Map(allSources.map((s) => [s.id, s]));
  return Array.from(scores.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([id]) => byId.get(id)!)
    .filter(Boolean);
}

/**
 * Map a prediction slug to its human-readable title.
 */
export function getPredictionTitle(slug: string): string {
  return slugToTitle[slug] ?? slug;
}

/**
 * Total number of searchable sources.
 */
export function getSourceCount(): number {
  return allSources.length;
}

/**
 * Count of sources per evidence tier (1-4).
 */
export function getSourceCountsByTier(): Record<number, number> {
  const counts: Record<number, number> = { 1: 0, 2: 0, 3: 0, 4: 0 };
  for (const s of allSources) {
    counts[s.evidenceTier] = (counts[s.evidenceTier] ?? 0) + 1;
  }
  return counts;
}
