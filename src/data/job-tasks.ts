/**
 * Job Task Visualizer Data
 *
 * Each job is broken into its component tasks (informed by O*NET work activities).
 * For each task we estimate:
 *   - timeShare: % of working hours spent on this task
 *   - currentComputeCostPerHr: what it costs today (2026) in $/hr to fully automate
 *   - aiCapability: 0-1 how capable current AI is at the task (1 = fully capable)
 *   - costDeclineRate: annual % decline in compute cost for this task type
 *   - category: broad O*NET work activity category
 *
 * Human wage is set per job. The crossover year for each task is when
 * computeCost * (1 - costDeclineRate)^years < humanWagePerHr * timeShare-adjusted cost.
 */

/**
 * Token economics model for computing AI task cost.
 * Cost_task = N × (T_i/1M × P_i + T_o/1M × P_o) × M
 *
 * Where:
 *   N  = model calls per hour of equivalent human work
 *   T_i, T_o = input/output tokens per call
 *   P_i, P_o = price per 1M input/output tokens
 *   M  = overhead multiplier (retries, RAG, tool calls: typically 2-6)
 */
export interface TokenProfile {
  modelTier: "small" | "mid" | "frontier";
  inputTokensPerCall: number;
  outputTokensPerCall: number;
  callsPerHumanHour: number;
  overheadMultiplier: number; // 2-6 typical
}

/**
 * Model tier pricing — 2026 blended rates based on leading providers.
 *
 * Small:    Haiku 4.5 ($0.80/$4), GPT-4o-mini ($0.15/$0.60), Gemini Flash ($0.075/$0.30).
 *           Blended average for classification/extraction workloads.
 * Mid:      Sonnet 4.6 ($3/$15), GPT-4o ($2.50/$10), Gemini Pro ($1.25/$5).
 *           Blended for drafting, chat, summarization.
 * Frontier: Opus 4.6 ($15/$75), o3 ($10/$40), Gemini Ultra ($5/$20).
 *           Used for complex reasoning, coding, expert analysis.
 *
 * These represent mid-2026 published API rates. Actual costs are declining
 * ~40-60% annually. The cost decline rate in each task captures this trend.
 */
export const MODEL_PRICING: Record<string, { inputPer1M: number; outputPer1M: number; label: string; examples: string }> = {
  small:    { inputPer1M: 0.25, outputPer1M: 1.00, label: "Small (classification, extraction)", examples: "Haiku 4.5, GPT-4o-mini, Gemini Flash" },
  mid:      { inputPer1M: 2.00, outputPer1M: 10.00, label: "Mid-tier (chat, drafting)", examples: "Sonnet 4.6, GPT-4o, Gemini Pro" },
  frontier: { inputPer1M: 10.00, outputPer1M: 50.00, label: "Frontier (reasoning, coding)", examples: "Opus 4.6, o3, Gemini Ultra" },
};

/** Calculate $/hr from token profile */
export function tokenCostPerHour(profile: TokenProfile): number {
  const pricing = MODEL_PRICING[profile.modelTier];
  const costPerCall =
    (profile.inputTokensPerCall / 1_000_000) * pricing.inputPer1M +
    (profile.outputTokensPerCall / 1_000_000) * pricing.outputPer1M;
  return costPerCall * profile.callsPerHumanHour * profile.overheadMultiplier;
}

