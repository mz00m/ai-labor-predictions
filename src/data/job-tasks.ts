/**
 * Deployment overhead: real-world automation costs beyond raw API calls.
 * Accounts for: integration engineering, error handling & retries, validation pipelines,
 * human-in-the-loop review, monitoring, edge case handling, and organizational adoption.
 * Production AI deployments typically cost 3-8x raw inference (Sequoia Capital 2025 data).
 * We use 5x as a conservative midpoint.
 */
export const DEPLOYMENT_OVERHEAD = 5;

/**
 * Calculate the year when compute cost crosses below human cost for a task.
 * Returns null if crossover doesn't happen within 20 years.
 *
 * Compute cost includes deployment overhead (integration, tooling, validation)
 * on top of raw API/inference costs, declining annually per task category.
 */
export function calculateCrossoverYear(
  task: JobTask,
  humanWagePerHr: number,
  baseYear: number = 2026
): number | null {
  // Crossover is when compute cost per hour of work drops below human wage per hour.
  // This is independent of timeShare - it reflects when the economics tip for this
  // task type at this wage level. TimeShare affects *exposure* (how much of your job
  // is affected), not *when* automation becomes viable.
  const computeCostPerHr = task.currentComputeCostPerHr * DEPLOYMENT_OVERHEAD;

  if (computeCostPerHr <= humanWagePerHr) return baseYear;

  for (let y = 1; y <= 20; y++) {
    const futureCost = computeCostPerHr * Math.pow(1 - task.costDeclineRate, y);
    if (futureCost <= humanWagePerHr) {
      return baseYear + y;
    }
  }
  return null;
}

/**
 * Generate cost trajectory data for a task over years.
 */
export function generateCostTrajectory(
  task: JobTask,
  humanWagePerHr: number,
  years: number = 10,
  baseYear: number = 2026
): { year: number; computeCost: number; humanCost: number }[] {
  const data = [];

  for (let y = 0; y <= years; y++) {
    const computeCost =
      task.currentComputeCostPerHr *
      DEPLOYMENT_OVERHEAD *
      Math.pow(1 - task.costDeclineRate, y);
    data.push({
      year: baseYear + y,
      computeCost: Math.round(computeCost * 100) / 100,
      humanCost: Math.round(humanWagePerHr * 100) / 100,
    });
  }
  return data;
}

/**
 * Get the token-based cost for a task, using task-specific overrides
 * or the default category profile.
 */
export function getTaskTokenCost(task: JobTask): {
  costPerHour: number;
  profile: TokenProfile;
  costPerCall: number;
} {
  const defaultProfile = CATEGORY_TOKEN_PROFILES[task.category];
  const profile: TokenProfile = {
    ...defaultProfile,
    ...(task.tokenProfile || {}),
  };
  const pricing = MODEL_PRICING[profile.modelTier];
  const costPerCall =
    (profile.inputTokensPerCall / 1_000_000) * pricing.inputPer1M +
    (profile.outputTokensPerCall / 1_000_000) * pricing.outputPer1M;
  const costPerHour = costPerCall * profile.callsPerHumanHour * profile.overheadMultiplier;
  return { costPerHour, profile, costPerCall };
}

/**
 * Calculate the probable adoption year for a task, accounting for
 * institutional drag (process change, training, regulation, trust)
 * and industry-level adoption speed.
 *
 * The industrySpeedMultiplier scales the task-category adoption lag:
 *   - 1.0 = baseline (default)
 *   - < 1.0 = faster adoption (e.g., tech industry at 0.6)
 *   - > 1.0 = slower adoption (e.g., healthcare at 1.4)
 *
 * Returns economic crossover year + adjusted adoption lag,
 * or null if crossover doesn't happen within 20 years.
 */
export function calculateAdoptionYear(
  task: JobTask,
  humanWagePerHr: number,
  baseYear: number = 2026,
  industrySpeedMultiplier: number = 1.0
): number | null {
  const crossover = calculateCrossoverYear(task, humanWagePerHr, baseYear);
  if (crossover === null) return null;
  const adjustedLag = CATEGORY_ADOPTION_LAG[task.category] * industrySpeedMultiplier;
  return Math.round((crossover + adjustedLag) * 10) / 10;
}

/**
 * Calculate overall job economic exposure score (0-100).
 */
export function calculateJobExposure(job: JobProfile): number {
  return Math.round(
    job.tasks.reduce((sum, task) => {
      const crossover = calculateCrossoverYear(task, job.medianWagePerHr);
      const yearsUntilCrossover = crossover ? crossover - 2026 : 20;
      // Tasks that cross over sooner and occupy more time = more exposure
      const taskExposure =
        task.timeShare * task.aiCapability * (1 - yearsUntilCrossover / 20);
      return sum + Math.max(0, taskExposure);
    }, 0) * 100
  );
}
