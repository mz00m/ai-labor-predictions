/**
 * Job Task Visualizer Data
 *
 * Each job is broken into its component tasks (informed by O*NET work activities).
 * For each task we estimate:
 *   - timeShare: % of working hours spent on this task
 *   - currentComputeCostPerHr: what it costs today (2026) in $/hr to fully automate
 *   - aiCapability: 0-1 how capable current AI is at the task (1 = fully capable)
 *   - costDeclineRate: annual % decline in compute cost for this task type
 *   - category: broad O*NET work activity category
 *
 * Human wage is set per job. The crossover year for each task is when
 * computeCost * (1 - costDeclineRate)^years < humanWagePerHr * timeShare-adjusted cost.
 */

export interface JobTask {
  id: string;
  name: string;
  description: string;
  timeShare: number; // 0-1, fraction of working hours
  currentComputeCostPerHr: number; // $/hr to automate this task fully in 2026
  aiCapability: number; // 0-1, current AI capability level
  costDeclineRate: number; // annual fractional decline (e.g. 0.40 = 40%/yr)
  category: TaskCategory;
}

export type TaskCategory =
  | "information-processing"
  | "communication"
  | "analysis-decision"
  | "creative-generative"
  | "coordination-management"
  | "physical-manual"
  | "interpersonal"
  | "technical-specialized";

